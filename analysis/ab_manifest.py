#!/usr/bin/env python3
"""Record exactly what produced the A/B pooled-extraction comparison.

A text diff of two score lists is not reproducible on its own. It does not say
which checkpoints were pooled, which snapshot state A was restored from, what
the code was, or when. This writes that alongside the outputs so the comparison
in Section 5.2 / 7.1 can be re-derived rather than taken on trust.

    python -m analysis.ab_manifest --snapshot backups/graphs_<ts>
"""
from __future__ import annotations

import argparse
import glob
import hashlib
import json
import os
import platform
import re
import subprocess
import sys
from datetime import datetime, timezone

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
AB = os.path.join(ROOT, "analysis", "ab")


def sh(*cmd: str) -> str:
    try:
        return subprocess.run(cmd, cwd=ROOT, capture_output=True,
                              text=True, timeout=20).stdout.strip()
    except Exception:
        return ""


def sha256(path: str) -> str | None:
    if not os.path.isfile(path):
        return None
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 16), b""):
            h.update(chunk)
    return h.hexdigest()


def scores(path: str) -> dict[str, float]:
    out: dict[str, float] = {}
    if not os.path.isfile(path):
        return out
    for line in open(path, encoding="utf-8"):
        m = re.match(r"\s+((?:study|ref)\d+)\s+([\d.]+)/100", line)
        if m:
            out[m.group(1)] = float(m.group(2))
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--snapshot", required=True)
    args = ap.parse_args()

    from rag_pipeline.model_registry import REGISTRY
    from analysis.pool_extractors import ALREADY_MERGED, DEFAULT_POOL

    def describe(key_or_slug: str) -> dict:
        """Exact provenance for one extractor, by registry key or output slug."""
        from rag_pipeline.grounded import model_slug
        for k, sp in REGISTRY.items():
            if k == key_or_slug or model_slug(sp.model) == key_or_slug:
                return {"registry_key": k, "identifier": sp.model,
                        "backend": sp.backend, "slug": model_slug(sp.model),
                        "contaminated": sp.contaminated, "scope": sp.scope,
                        "note": sp.note}
        return {"registry_key": None, "identifier": key_or_slug,
                "slug": key_or_slug,
                "note": "not in the registry; recorded as named"}

    a, b = scores(f"{AB}/fairr_A.txt"), scores(f"{AB}/fairr_B.txt")
    common = sorted(set(a) & set(b))
    moved = {k: {"A": a[k], "B": b[k], "delta": round(b[k] - a[k], 2)}
             for k in common if abs(a[k] - b[k]) > 1e-9}

    man = {
        "created_utc": datetime.now(timezone.utc).isoformat(),
        "what": ("A/B of FAIR-R and the Phase IV predictor analysis under "
                 "single-extractor versus pooled extraction."),
        "state_A": {
            "label": "Mistral-24B only, as the canonical graphs were built 2 Sep 2026",
            "extractors": [describe(s) for s in ALREADY_MERGED],
            "restored_from_snapshot": os.path.basename(args.snapshot.rstrip("/")),
        },
        "state_B": {
            "label": "pooled: the above plus three uncontaminated full-corpus models",
            "extractors": [describe(s) for s in ALREADY_MERGED + DEFAULT_POOL],
            "excluded": {
                "gemini-flash": "reference generated by this model family",
                "opus": ("covers 12 of 95 studies; pooling would confound the "
                         "audited tier with deeper extraction"),
            },
        },
        "result": {
            "studies_compared": len(common),
            "unchanged": len(common) - len(moved),
            "moved": moved,
            "mean_delta_points": (round(sum(b[k] - a[k] for k in common) / len(common), 3)
                                  if common else None),
        },
        "code": {
            "git_commit": sh("git", "rev-parse", "HEAD"),
            "git_branch": sh("git", "rev-parse", "--abbrev-ref", "HEAD"),
            "git_dirty": bool(sh("git", "status", "--porcelain")),
            "python": platform.python_version(),
            "host": platform.node(),
        },
        "outputs": {os.path.basename(p): {"sha256": sha256(p),
                                          "bytes": os.path.getsize(p)}
                    for p in sorted(glob.glob(f"{AB}/*"))
                    if os.path.isfile(p) and not p.endswith("RUN.json")},
        "snapshot": {
            "path": args.snapshot,
            "manifest_sha256": sha256(os.path.join(args.snapshot, "MANIFEST.json")),
        },
        "how_to_reproduce": [
            "python -m analysis.pool_extractors snapshot",
            f"bash cluster/ab_pool_compare.sh {args.snapshot}",
            "python -m analysis.ab_manifest --snapshot <that snapshot>",
        ],
    }
    os.makedirs(AB, exist_ok=True)
    out = os.path.join(AB, "RUN.json")
    json.dump(man, open(out, "w", encoding="utf-8"), indent=2)
    print(f"  wrote {out}")
    print(f"  {man['result']['studies_compared']} studies, "
          f"{man['result']['unchanged']} unchanged, {len(moved)} moved, "
          f"mean {man['result']['mean_delta_points']:+} points")
    for k, v in sorted(moved.items(), key=lambda t: -t[1]["delta"]):
        print(f"    {k}  {v['A']} -> {v['B']}  {v['delta']:+}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
