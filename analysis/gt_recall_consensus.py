"""Estimate ground-truth recall from cross-model consensus (no API calls).

The reference standard was generated by one model family and verified by one
person, 24 files at `thorough` depth and 83 at `standard`. The RQ3 scores
behave like a reference that under-lists rather than like models that
hallucinate: across eight extractors, items-per-study correlates -0.76 with
precision and only +0.48 with recall, so the ranking is close to a ranking by
restraint. That is a hypothesis about the reference, and this module tests it
without a human and without spending anything.

The argument. Eight extractions exist per study, from seven organisations. If
many of them independently produce an item the reference does not contain, the
likelier explanation is a gap in the reference than simultaneous identical
hallucination. That is an assumption, so it is calibrated rather than asserted:
the same statistic is computed separately over the `thorough` and `standard`
files. If consensus-missing items are rarer where verification was careful, the
gap tracks verification depth and the assumption holds. If the rate is flat,
consensus is picking up shared model bias and these counts mean much less.

Normalisation is imported from the annotation bundle builder so that an item
counted here is the same string an annotator would judge.

    python3 analysis/gt_recall_consensus.py --min-frac 0.6
"""
from __future__ import annotations

import argparse, csv, json, os, sys, collections

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from evaluation.build_annotation_bundles import (          # noqa: E402
    GT, EXTRACT, GOLD_FIELDS, MODEL_FIELDS, FIELD_ORDER,
    render, canon, environment_items, load_json,
)


def gold_for(study_id):
    for tier in ("gold", "silver"):
        p = os.path.join(GT, tier, study_id, "gold_standard.json")
        if os.path.exists(p):
            return load_json(p), tier
    return None, None


def rendered(field, entries):
    if field == "environment":
        return environment_items(entries)
    return [render(field, it) for it in (entries or [])]


def collect(study_id):
    """-> (gold_keys, {field: {canon: {'models': set, 'text': str}}})"""
    gold, _ = gold_for(study_id)
    gold_keys = {f: set() for f in FIELD_ORDER}
    if gold:
        for gkey, field in GOLD_FIELDS.items():
            for r in rendered(field, (gold.get("entities") or {}).get(gkey)):
                if r.strip():
                    gold_keys[field].add(canon(field, r))

    pool = {f: {} for f in FIELD_ORDER}
    models = set()
    for fname in sorted(os.listdir(EXTRACT)):
        if not fname.startswith(study_id + "__") or not fname.endswith(".json"):
            continue
        slug = fname[len(study_id) + 2:-5]
        models.add(slug)
        meta = (load_json(os.path.join(EXTRACT, fname)) or {}).get("metadata") or {}
        for mkey, field in MODEL_FIELDS.items():
            if meta.get(mkey) is None:
                continue
            for r in rendered(field, meta.get(mkey)):
                if not r.strip():
                    continue
                c = canon(field, r)
                e = pool[field].setdefault(c, {"models": set(), "text": r})
                e["models"].add(slug)
    return gold_keys, pool, models


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--min-frac", type=float, default=0.6,
                    help="fraction of available models that must agree (default 0.6)")
    ap.add_argument("--out-csv", default=os.path.join(ROOT, "analysis",
                                                      "gt_consensus_candidates.csv"))
    ap.add_argument("--out-md", default=os.path.join(ROOT, "analysis",
                                                     "gt_recall_consensus.md"))
    args = ap.parse_args()

    studies = sorted({os.path.basename(os.path.dirname(p))
                      for tier in ("gold", "silver")
                      for p in [os.path.join(GT, tier, d, "gold_standard.json")
                                for d in (os.listdir(os.path.join(GT, tier))
                                          if os.path.isdir(os.path.join(GT, tier)) else [])]
                      if os.path.exists(p)})

    by_depth = collections.defaultdict(lambda: collections.Counter())
    per_field = collections.defaultdict(lambda: collections.Counter())
    rows = []

    for sid in studies:
        gold, _ = gold_for(sid)
        depth = (gold or {}).get("_verification_depth") or "unrecorded"
        gold_keys, pool, models = collect(sid)
        n_models = len(models)
        if not n_models:
            continue
        need = max(2, int(round(args.min_frac * n_models)))

        for field in FIELD_ORDER:
            g = gold_keys[field]
            by_depth[depth]["gold_items"] += len(g)
            per_field[field]["gold_items"] += len(g)
            for c, e in pool[field].items():
                k = len(e["models"])
                if c in g:
                    by_depth[depth]["gold_confirmed"] += 1
                    per_field[field]["gold_confirmed"] += 1
                elif k >= need:
                    by_depth[depth]["consensus_missing"] += 1
                    per_field[field]["consensus_missing"] += 1
                    rows.append({
                        "study_id": sid, "tier_depth": depth, "field": field,
                        "item": e["text"], "n_models": k, "of_models": n_models,
                        "agreement": round(k / n_models, 2),
                        "models": ";".join(sorted(e["models"])),
                    })
            # gold items no model proposed
            proposed = set(pool[field])
            by_depth[depth]["gold_unmatched"] += len(g - proposed)
            per_field[field]["gold_unmatched"] += len(g - proposed)

    rows.sort(key=lambda r: (-r["agreement"], r["field"], r["study_id"]))
    os.makedirs(os.path.dirname(args.out_csv), exist_ok=True)
    with open(args.out_csv, "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0]) if rows else
                           ["study_id","tier_depth","field","item","n_models",
                            "of_models","agreement","models"])
        w.writeheader(); w.writerows(rows)

    L = ["# Ground-truth recall, estimated from cross-model consensus", "",
         f"Consensus threshold: an item counts as consensus-missing when at least "
         f"{args.min_frac:.0%} of the extractors available for that study produced "
         f"it and the reference does not contain it.", "",
         "## Calibration against verification depth", "",
         "If the reference's gaps come from light verification, consensus-missing "
         "items should be rarer where verification was thorough. If the rate is "
         "flat, consensus is measuring shared model bias instead.", "",
         "| depth | gold items | consensus-missing | missing per gold item | est. recall |",
         "|---|---:|---:|---:|---:|"]
    for d in sorted(by_depth):
        c = by_depth[d]; gi = c["gold_items"]; cm = c["consensus_missing"]
        ratio = cm / gi if gi else float("nan")
        rec = gi / (gi + cm) if (gi + cm) else float("nan")
        L.append(f"| `{d}` | {gi} | {cm} | {ratio:.2f} | {rec:.1%} |")

    L += ["", "## By field", "",
          "| field | gold items | consensus-missing | est. recall | gold items no model proposed |",
          "|---|---:|---:|---:|---:|"]
    for f in FIELD_ORDER:
        c = per_field[f]; gi = c["gold_items"]; cm = c["consensus_missing"]
        rec = gi / (gi + cm) if (gi + cm) else float("nan")
        L.append(f"| `{f}` | {gi} | {cm} | {rec:.1%} | {c['gold_unmatched']} |")

    tg = sum(by_depth[d]['gold_items'] for d in by_depth)
    tc = sum(by_depth[d]['consensus_missing'] for d in by_depth)
    L += ["", "## Overall", "",
          f"- reference items: **{tg}**",
          f"- consensus-missing candidates: **{tc}**",
          f"- implied reference recall: **{tg/(tg+tc):.1%}**" if tg+tc else "",
          f"- candidate list for adjudication: `{os.path.relpath(args.out_csv, ROOT)}` "
          f"({len(rows)} rows, ranked by agreement)", "",
          "Consensus is not truth. These are candidates for a human to adjudicate, "
          "and the calibration table above is what says how much weight they carry."]
    with open(args.out_md, "w", encoding="utf-8") as fh:
        fh.write("\n".join(L) + "\n")
    print("\n".join(L))
    return 0


if __name__ == "__main__":
    sys.exit(main())
